import {
  getLockedActionRefs,
  normalizeWorkflowPath,
  parseWorkflowLockfileContents,
  readWorkflowLockfile,
  toActionPinKey,
  WorkflowLockfile,
} from "../lockfile.js";
import path from "node:path";

import { vi, describe, it, expect } from "vitest";

vi.mock("@actions/core", async () => {
  return (await import("./__helpers__/test-utils.js")).coreLoggingStubs();
});

const LOCKFILE_FIXTURE_DIR = path.join(
  __dirname,
  "__fixtures__",
  "lockfile-repo",
);

const LOCKFILE_CONTENT = `# This file is machine-generated by \`gh actions-lock\`.
version: 'v0.0.3'
workflows:
    '.github/workflows/ci.yml':
        - 'actions/checkout@v6'
        - 'dorny/paths-filter@v3.0.2'
dependencies:
    'actions/checkout@v6':
        ref: 'v6'
        commit: 'sha1-aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa'
        owner_id: 44036562
        repo_id: 197814629
    'dorny/paths-filter@v3.0.2':
        ref: 'v3.0.2'
        commit: 'sha1-bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb'
        owner_id: 44036562
        repo_id: 197814629
`;

describe(parseWorkflowLockfileContents.name, () => {
  it("parses workflows with the official parser", async () => {
    const result = await parseWorkflowLockfileContents(LOCKFILE_CONTENT);

    expect(result.error).toBeUndefined();
    expect(result.lockfile).toEqual({
      version: "v0.0.3",
      workflows: {
        ".github/workflows/ci.yml": [
          "actions/checkout@v6",
          "dorny/paths-filter@v3.0.2",
        ],
      },
    } satisfies WorkflowLockfile);
  });

  it("rejects workflow paths that escape the repository", async () => {
    const result = await parseWorkflowLockfileContents(`version: v0.0.3
workflows:
  ../../etc/passwd:
    - actions/checkout@v6
`);

    expect(result.lockfile).toBeUndefined();
    expect(result.error?.message).toContain("path traversal");
    expect(result.error?.line).toBeGreaterThan(0);
  });

  it("rejects unknown top-level fields", async () => {
    const result = await parseWorkflowLockfileContents(`version: v0.0.3
workflows: {}
unexpected: true
`);

    expect(result.lockfile).toBeUndefined();
    expect(result.error?.message).toContain("unknown lockfile field");
  });
});

describe(readWorkflowLockfile.name, () => {
  it("reads and validates the lockfile from the repository root", async () => {
    const result = await readWorkflowLockfile(LOCKFILE_FIXTURE_DIR);

    expect(result.error).toBeUndefined();
    expect(result.lockfile?.workflows[".github/workflows/ci.yml"]).toEqual([
      "actions/checkout@v6",
      "dorny/paths-filter@v3.0.2",
    ]);
  });

  it("returns no result and no error when there is no lockfile", async () => {
    const result = await readWorkflowLockfile(
      path.join(__dirname, "__fixtures__"),
    );

    expect(result).toEqual({});
  });
});

describe(normalizeWorkflowPath.name, () => {
  it("strips a leading ./", () => {
    expect(normalizeWorkflowPath("./.github/workflows/ci.yml")).toBe(
      ".github/workflows/ci.yml",
    );
  });

  it("converts backslashes", () => {
    expect(normalizeWorkflowPath(".github\\workflows\\ci.yml")).toBe(
      ".github/workflows/ci.yml",
    );
  });

  it("makes absolute paths relative to the root directory", () => {
    expect(
      normalizeWorkflowPath("/repo/.github/workflows/ci.yml", "/repo"),
    ).toBe(".github/workflows/ci.yml");
  });
});

describe(toActionPinKey.name, () => {
  it("lowercases owner and repo and preserves the ref", () => {
    expect(toActionPinKey("Actions", "Checkout", "v4.2.1")).toBe(
      "actions/checkout@v4.2.1",
    );
  });
});

describe(getLockedActionRefs.name, () => {
  const lockfile: WorkflowLockfile = {
    workflows: {
      ".github/workflows/ci.yml": ["actions/cache@v4"],
    },
  };

  it("returns refs for an onboarded workflow", () => {
    expect(
      getLockedActionRefs(
        lockfile,
        "./.github/workflows/ci.yml",
        LOCKFILE_FIXTURE_DIR,
      ),
    ).toEqual(["actions/cache@v4"]);
  });

  it("returns undefined for a workflow that is not onboarded", () => {
    expect(
      getLockedActionRefs(lockfile, ".github/workflows/other.yml"),
    ).toBeUndefined();
  });

  it("returns undefined when there is no lockfile", () => {
    expect(
      getLockedActionRefs(undefined, ".github/workflows/ci.yml"),
    ).toBeUndefined();
  });
});
